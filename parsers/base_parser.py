"""
Базовый класс для парсеров (теперь только через браузер)
"""
from abc import ABC, abstractmethod
from typing import List
from models.product import Product


class ShopCheckError(Exception):
    """Магазин НЕ удалось проверить (а не «новых товаров нет»).

    Критично: раньше парсер возвращал пустой список и при ошибке, и когда
    товаров действительно нет. Вызывающий код показывал «не удалось получить
    товары» в обоих случаях, поэтому в логе было невозможно отличить
    сломанный/недоступный магазин от просто пустого.

    Пустой список [] теперь означает ровно одно: магазин проверили, новых
    товаров нет. Всё, что помешало проверке, — это исключение.
    """


class BaseParser(ABC):
    """Базовый класс для всех парсеров"""

    def __init__(self, config):
        self.config = config

    @abstractmethod
    def parse_shop_page(self, shop_url: str) -> List[Product]:
        """Парсит страницу магазина и возвращает список продуктов.

        Возвращает [] если новых товаров нет.
        Бросает ShopCheckError если магазин проверить не удалось.
        """
        pass
    
    @abstractmethod
    def get_shop_name_from_url(self, url: str) -> str:
        """Извлекает название магазина из URL"""
        pass